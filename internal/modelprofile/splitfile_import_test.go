// TestFinalManifestExtensionWithSplitFilesStillComparesTheRest leaves only
// split_file to the split file check: any other envelope change, a changed
// legacy permission seal or a changed training window is still refused.
func TestFinalManifestExtensionWithSplitFilesStillComparesTheRest(t *testing.T) {
	trainingFile, finalFile := pipelineTrainingSplitFile(), pipelineFinalSplitFile()
	finalBase := pipelineTestManifest(t, pipelineTestOptions{})
	trainingBase := pipelineTrainingManifest(t, finalBase)
	final := withPipelineSplitFile(t, finalBase, finalFile)
	training := withPipelineSplitFile(t, trainingBase, trainingFile)
	dir := t.TempDir()
	finalPath := writePipelineJSON(t, mkdir(t, dir, "final"), "manifest.json", final).Path
	trainingPath := writePipelineJSON(t, mkdir(t, dir, "training"), "manifest.json", training).Path
	writePipelineBytes(t, filepath.Dir(finalPath), dataset.SplitFileSidecar, finalFile)
	writePipelineBytes(t, filepath.Dir(trainingPath), dataset.SplitFileSidecar, trainingFile)

	extension, err := validateFinalManifestExtension(training, final, trainingPath, finalPath)
	require.NoError(t, err)
	require.NotNil(t, extension.splitFiles, "split_file differs, so the split files must still be verified")

	otherForm := final
	otherForm.ScreenForm = dataset.ScreenFormLive
	_, err = validateFinalManifestExtension(training, otherForm, trainingPath, finalPath)
	require.ErrorContains(t, err, "changes the training manifest envelope")

	_, err = validateFinalManifestExtension(
		manifestWithPermissionEvidenceLegacy(t, training, "a"),
		manifestWithPermissionEvidenceLegacy(t, final, "b"),
		trainingPath, finalPath)
	require.ErrorContains(t, err, "changes the training manifest envelope")

	changedEntry := final
	changedEntry.Entries = append([]dataset.ManifestEntry(nil), final.Entries...)
	for i, entry := range changedEntry.Entries {
		if entry.GroupDigest == training.Entries[0].GroupDigest {
			changedEntry.Entries[i].Label = dataset.LabelB
		}
	}
	_, err = validateFinalManifestExtension(training, changedEntry, trainingPath, finalPath)
	require.ErrorContains(t, err, "removes or changes a training window")

	require.NoError(t, os.WriteFile(filepath.Join(filepath.Dir(trainingPath), dataset.SplitFileSidecar),
		[]byte(strings.ToUpper(string(trainingFile))), 0o600))
	_, err = validateFinalManifestExtension(training, final, trainingPath, finalPath)
	require.ErrorContains(t, err, "training manifest split file")
}

func mkdir(t *testing.T, parent, name string) string {
	t.Helper()
	dir := filepath.Join(parent, name)
	require.NoError(t, os.Mkdir(dir, 0o700))
	return dir
}
