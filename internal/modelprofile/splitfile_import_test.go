// sidecarPath is the split-file.jsonl next to a manifest.
func sidecarPath(manifestPath string) string {
	return filepath.Join(filepath.Dir(manifestPath), dataset.SplitFileSidecar)
}

// TestRegisterPipelineImportsVerifiedSplitFileExtension imports a final
// manifest whose split file is the training split file plus the blind-test
// session: split_file differs, both sidecars verify, and registration goes
// through.
func TestRegisterPipelineImportsVerifiedSplitFileExtension(t *testing.T) {
	fixture := newServiceFixture(t)
	final := pipelineFinalSplitFile()
	bundle := writePipelineTestBundle(t, fixture, pipelineTestOptions{splitFiles: &pipelineSplitFiles{
		training: pipelineTrainingSplitFile(), final: final,
	}})

	registered, err := fixture.service.RegisterPipeline(t.Context(), bundle.request, operator())
	require.NoError(t, err)
	require.True(t, registered.Imported)
	assertPipelineRowCounts(t, fixture, 1, 1, 1, 4, 1)
	var split string
	require.NoError(t, fixture.store.DB().QueryRowContext(t.Context(),
		`SELECT split_strategy FROM dataset_versions`).Scan(&split))
	require.Equal(t, "split-file:"+string(dataset.SplitFileDigest(final)), split)
}

// TestRegisterPipelineSplitFileSidecarAddedAfterTheSeal seals the training
// dataset without a sidecar, as a build from before it existed does. The
// import refuses it until the sidecar is added with the exact bytes whose
// SHA-256 was sealed; regenerated bytes are refused.
func TestRegisterPipelineSplitFileSidecarAddedAfterTheSeal(t *testing.T) {
	fixture := newServiceFixture(t)
	training := pipelineTrainingSplitFile()
	bundle := writePipelineTestBundle(t, fixture, pipelineTestOptions{splitFiles: &pipelineSplitFiles{
		training: training, final: pipelineFinalSplitFile(),
	}})
	sidecar := sidecarPath(bundle.request.FinalEvaluation.TrainingManifest.Path)
	require.NoError(t, os.Remove(sidecar))

	_, err := fixture.service.RegisterPipeline(t.Context(), bundle.request, operator())
	require.ErrorIs(t, err, ErrRegistryInvalid, "no sidecar yet")
	assertPipelineRowCounts(t, fixture, 0, 0, 0, 0, 0)

	first, rest, _ := bytes.Cut(training, []byte("\n"))
	regenerated := append(append(append([]byte(nil), rest...), first...), '\n')
	require.NoError(t, os.WriteFile(sidecar, regenerated, 0o600))
	_, err = fixture.service.RegisterPipeline(t.Context(), bundle.request, operator())
	require.ErrorIs(t, err, ErrRegistryInvalid, "the same sessions, other bytes")
	assertPipelineRowCounts(t, fixture, 0, 0, 0, 0, 0)

	require.NoError(t, os.WriteFile(sidecar, training, 0o600))
	registered, err := fixture.service.RegisterPipeline(t.Context(), bundle.request, operator())
	require.NoError(t, err)
	require.True(t, registered.Imported)
	assertPipelineRowCounts(t, fixture, 1, 1, 1, 4, 1)
}

// TestRegisterPipelineRejectsSplitFileExtensionBeforeWrites refuses every
// split file failure before anything is written.
func TestRegisterPipelineRejectsSplitFileExtensionBeforeWrites(t *testing.T) {
	training := pipelineTrainingSplitFile()
	final := pipelineFinalSplitFile()
	first, rest, _ := bytes.Cut(training, []byte("\n"))
	reordered := append(append(append([]byte(nil), rest...), first...), '\n')
	blind := final[len(training):]
	for _, test := range []struct {
		name   string
		files  pipelineSplitFiles
		mutate func(*testing.T, pipelineTestBundle)
		want   string
	}{
		{
			name: "final sidecar missing", files: pipelineSplitFiles{training: training, final: final},
			want: "final manifest split file: open split-file.jsonl",
			mutate: func(t *testing.T, bundle pipelineTestBundle) {
				require.NoError(t, os.Remove(sidecarPath(bundle.request.Manifest.Path)))
			},
		},
		{
			name: "final sidecar with other bytes", files: pipelineSplitFiles{training: training, final: final},
			want: "final manifest split file: evidence digest mismatch",
			mutate: func(t *testing.T, bundle pipelineTestBundle) {
				require.NoError(t, os.WriteFile(sidecarPath(bundle.request.Manifest.Path), append(final, '\n'), 0o600))
			},
		},
		{name: "final split file over 1 MiB", files: pipelineSplitFiles{
			training: training, final: append(append([]byte(nil), final...), bytes.Repeat([]byte("\n"), dataset.MaxSplitFileBytes)...),
		}, want: "final manifest split file: evidence file is not a bounded regular file"},
		{
			name: "the training manifest names no split file", files: pipelineSplitFiles{final: final},
			want: "final manifest changes the training manifest envelope",
		},
		{name: "an extra test session", files: pipelineSplitFiles{
			training: training, final: append(append([]byte(nil), final...), pipelineSplitLine("pipeline-extra-session", dataset.SplitTest)...),
		}, want: "adds a session that is not blind-test"},
		{
			name: "a blind session the final split file does not add", files: pipelineSplitFiles{training: training, final: final},
			want: "misses a blind-test session",
			mutate: func(t *testing.T, bundle pipelineTestBundle) {
				raw := []byte(`{"session_id":"` + pipelineBlindSession + `"}` + "\n" +
					`{"session_id":"` + pipelineBlindSession + `-2"}` + "\n")
				list := &bundle.request.FinalEvaluation.BlindTestSessions
				require.NoError(t, os.WriteFile(list.Path, raw, 0o600))
				list.SHA256 = digestBytes(raw)
			},
		},
		{
			name: "blanks only", files: pipelineSplitFiles{training: training, final: append(append([]byte(nil), training...), '\n')},
			want: "the final split file adds no session",
		},
		{
			name: "training lines reordered", files: pipelineSplitFiles{training: training, final: append(reordered, blind...)},
			want: "does not start with the training split file",
		},
		{name: "the blind session not test", files: pipelineSplitFiles{
			training: training, final: append(append([]byte(nil), training...), pipelineSplitLine(pipelineBlindSession, dataset.SplitValidation)...),
		}, want: "adds a session that is not test"},
	} {
		t.Run(test.name, func(t *testing.T) {
			fixture := newServiceFixture(t)
			files := test.files
			bundle := writePipelineTestBundle(t, fixture, pipelineTestOptions{splitFiles: &files})
			if test.mutate != nil {
				test.mutate(t, bundle)
			}
			_, err := preparePipelineImport(bundle.request)
			require.ErrorContains(t, err, test.want)
			require.NotContains(t, err.Error(), "pipeline-", "the error names no session")
			_, err = fixture.service.RegisterPipeline(t.Context(), bundle.request, operator())
			require.ErrorIs(t, err, ErrRegistryInvalid)
			assertPipelineRowCounts(t, fixture, 0, 0, 0, 0, 0)
		})
	}
}

